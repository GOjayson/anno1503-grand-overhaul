def localized_sample_baselines(locale: str) -> dict[str, tuple[int, str]]:
    """Return sample basenames mapped to the original byte length and SHA-1."""
    if locale not in _LOCALES:
        raise ValueError(f"Unknown History Edition sample locale: {locale}")

    baselines = _ENGLISH_BASELINES.copy()
    for name, overrides in _LOCALIZED_BASELINE_OVERRIDES.items():
        for locales, fingerprint in overrides:
            if locale in locales:
                baselines[name] = fingerprint
                break
    return baselines
